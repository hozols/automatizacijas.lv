// Usage: node scripts/fetch-paintings.mjs
// Downloads the Met Open Access paintings listed in docs/paintings.json, writes the
// WebP variants into public/paintings and regenerates docs/paintings.md (credits).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import sharp from 'sharp';
import { validateManifest, creditLine, outputNames } from './paintings-core.mjs';

const manifest = JSON.parse(readFileSync('docs/paintings.json', 'utf8'));
const errors = validateManifest(manifest);
if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const outDir = 'public/paintings';
mkdirSync(outDir, { recursive: true });
const tmp = path.join(os.tmpdir(), 'met-paintings');
mkdirSync(tmp, { recursive: true });

const credits = [];
for (const entry of manifest) {
  const meta = await (await fetch(`https://collectionapi.metmuseum.org/public/collection/v1/objects/${entry.metObjectId}`)).json();
  if (!meta.isPublicDomain) throw new Error(`${entry.slug}: object ${entry.metObjectId} is not public domain`);
  if (!meta.primaryImage) throw new Error(`${entry.slug}: object ${entry.metObjectId} has no primary image`);
  const buf = Buffer.from(await (await fetch(meta.primaryImage)).arrayBuffer());
  const src = path.join(tmp, `${entry.slug}.jpg`);
  writeFileSync(src, buf);

  const { wide, square } = outputNames(entry.slug, outDir);
  const image = sharp(src);
  const { width, height } = await image.metadata();
  await sharp(src).resize({ width: 1600, withoutEnlargement: true }).webp({ quality: 78 }).toFile(wide);

  // square crop around the focus point
  const side = Math.min(width, height);
  const left = Math.round(Math.min(Math.max(entry.focus.x * width - side / 2, 0), width - side));
  const top = Math.round(Math.min(Math.max(entry.focus.y * height - side / 2, 0), height - side));
  await sharp(src).extract({ left, top, width: side, height: side }).resize(800, 800).webp({ quality: 80 }).toFile(square);
  await sharp(src).extract({ left, top, width: side, height: side }).resize(400, 400).webp({ quality: 80 }).toFile(square.replace('-800.webp', '-400.webp'));

  credits.push({ slug: entry.slug, use: entry.use, line: creditLine(meta) });
  console.log('ok  ', entry.slug, '|', meta.title, '|', `${width}x${height}`);
}

const md = [
  '# Paintings',
  '',
  'All images are from The Metropolitan Museum of Art Open Access collection (CC0). Generated by `npm run paintings` from `docs/paintings.json`.',
  '',
  '| Slug | Use | Credit |',
  '| --- | --- | --- |',
  ...credits.map((c) => `| \`${c.slug}\` | ${c.use} | ${c.line} |`),
  '',
].join('\n');
writeFileSync('docs/paintings.md', md);
console.log(`\nwrote ${credits.length} paintings and docs/paintings.md`);
